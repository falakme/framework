//! TypeScript client generated from the IR (T1.15, `falak sync`).
//!
//! The output is one file with the record types, create and update bodies, and an
//! API class per entity built on `@falak/sdk`. It depends only on the IR, so output is
//! stable and a CI check can fail when a checked-in copy is out of date.

use std::fmt::Write;

use falak_contracts::ir::{FieldType, Ir, IrAction, IrCommand, IrCommandKind, IrEntity, IrField};

use crate::openapi::writable;

/// Generate the client source for an app.
pub fn generate(ir: &Ir) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by `falak sync` from {} {} (ir sha256:{}). Do not edit.",
        ir.app.name, ir.app.version, ir.content_hash
    );
    out.push_str("// int64 and decimal_minor fields are `number`: exact up to 2^53 - 1.\n\n");
    out.push_str(
        "import { FalakClient, Resource, type ClientOptions, type WriteOptions } from \"@falak/sdk\";\n\n",
    );

    for entity in &ir.entities {
        entity_types(&mut out, entity);
        entity_class(&mut out, ir, entity);
    }
    app_client(&mut out, ir);
    out
}

fn ts_type(ty: &FieldType) -> &'static str {
    match ty {
        FieldType::Uuid | FieldType::Text | FieldType::Timestamptz | FieldType::Bytes => "string",
        FieldType::Int64 | FieldType::DecimalMinor => "number",
        FieldType::Bool => "boolean",
        FieldType::Json => "unknown",
    }
}

fn field_type(field: &IrField) -> String {
    let base = ts_type(&field.ty);
    if field.nullable && base != "unknown" {
        format!("{base} | null")
    } else {
        base.to_string()
    }
}

fn pascal(name: &str) -> String {
    name.split('_')
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn camel(name: &str) -> String {
    let p = pascal(name);
    let mut c = p.chars();
    c.next()
        .map(|f| f.to_ascii_lowercase().to_string() + c.as_str())
        .unwrap_or_default()
}

fn entity_types(out: &mut String, entity: &IrEntity) {
    let name = pascal(&entity.name);

    let _ = writeln!(out, "/** A {} as the API returns it. */", entity.name);
    let _ = writeln!(out, "export interface {name} {{");
    for f in &entity.fields {
        let _ = writeln!(out, "  {}: {};", f.name, field_type(f));
    }
    out.push_str("}\n\n");

    let _ = writeln!(
        out,
        "/** Body to create a {}. The owner and built-in fields are set by the server. */",
        entity.name
    );
    let _ = writeln!(out, "export interface {name}Create {{");
    for f in writable(entity) {
        let optional = f.nullable || f.default.is_some();
        let _ = writeln!(
            out,
            "  {}{}: {};",
            f.name,
            if optional { "?" } else { "" },
            field_type(f)
        );
    }
    out.push_str("}\n\n");

    let _ = writeln!(out, "/** Fields to change on a {}. */", entity.name);
    let _ = writeln!(out, "export interface {name}Update {{");
    for f in writable(entity) {
        let _ = writeln!(out, "  {}?: {};", f.name, field_type(f));
    }
    out.push_str("}\n\n");
}

fn command_action(c: &IrCommand) -> IrAction {
    match c.kind {
        IrCommandKind::Create => IrAction::Create,
        IrCommandKind::Delete => IrAction::Delete,
        IrCommandKind::Update | IrCommandKind::Custom => IrAction::Update,
    }
}

fn allowed(entity: &IrEntity, action: IrAction) -> bool {
    entity
        .policy
        .rules
        .iter()
        .any(|r| r.actions.contains(&action))
}

fn entity_class(out: &mut String, ir: &Ir, entity: &IrEntity) {
    let name = pascal(&entity.name);
    let _ = writeln!(
        out,
        "export class {name}Api extends Resource<{name}, {name}Create, {name}Update> {{"
    );
    out.push_str("  constructor(client: FalakClient) {\n");
    let _ = writeln!(
        out,
        "    super(client, \"{}\", \"{}\");",
        entity.name, entity.table
    );
    out.push_str("  }\n");

    for command in ir.commands.iter().filter(|c| c.entity == entity.name) {
        if !allowed(entity, command_action(command)) {
            continue;
        }
        let inputs: Vec<_> = command
            .input
            .iter()
            .filter(|i| Some(&i.name) != command.target.as_ref())
            .collect();
        out.push('\n');
        let _ = writeln!(out, "  /** Run `{}` on a {}. */", command.name, entity.name);
        if inputs.is_empty() {
            let _ = writeln!(
                out,
                "  {}(id: string, options?: WriteOptions): Promise<{name}> {{",
                camel(&command.name)
            );
            let _ = writeln!(
                out,
                "    return this.run(id, \"{}\", {{}}, options);",
                command.name
            );
        } else {
            let fields: Vec<String> = inputs
                .iter()
                .map(|i| {
                    format!(
                        "{}{}: {}",
                        i.name,
                        if i.required { "" } else { "?" },
                        ts_type(&i.ty)
                    )
                })
                .collect();
            let _ = writeln!(
                out,
                "  {}(id: string, input: {{ {} }}, options?: WriteOptions): Promise<{name}> {{",
                camel(&command.name),
                fields.join("; ")
            );
            let _ = writeln!(
                out,
                "    return this.run(id, \"{}\", input, options);",
                command.name
            );
        }
        out.push_str("  }\n");
    }
    out.push_str("}\n\n");
}

fn app_client(out: &mut String, ir: &Ir) {
    let class = format!("{}Client", pascal(&ir.app.name.replace('-', "_")));
    let _ = writeln!(out, "/** One property per entity. */");
    let _ = writeln!(out, "export class {class} {{");
    out.push_str("  readonly client: FalakClient;\n");
    for e in &ir.entities {
        let _ = writeln!(
            out,
            "  readonly {}: {}Api;",
            camel(&e.table),
            pascal(&e.name)
        );
    }
    out.push_str("\n  constructor(options: ClientOptions) {\n");
    out.push_str("    this.client = new FalakClient(options);\n");
    for e in &ir.entities {
        let _ = writeln!(
            out,
            "    this.{} = new {}Api(this.client);",
            camel(&e.table),
            pascal(&e.name)
        );
    }
    out.push_str("  }\n}\n\n");
    let _ = writeln!(
        out,
        "export function createClient(options: ClientOptions): {class} {{\n  return new {class}(options);\n}}"
    );
}
