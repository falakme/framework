//! Renders `falak.lock`: the pinned framework, IR and source versions for a build.

use falak_contracts::ir::Ir;

use crate::{build::sha256_hex, load::SourceFile};

pub const LOCK_VERSION: u32 = 1;

/// Render the lock file. Output depends only on its inputs, so it is stable across
/// machines and runs.
pub fn render(ir: &Ir, framework_version: &str, sources: &[SourceFile]) -> String {
    let mut files: Vec<&SourceFile> = sources.iter().collect();
    files.sort_by(|a, b| a.path.cmp(&b.path));
    let mut out = String::new();
    out.push_str("# Generated by `falak build`. Do not edit.\n");
    out.push_str(&format!("lock_version = {LOCK_VERSION}\n"));
    out.push_str(&format!("framework = \"{framework_version}\"\n"));
    out.push_str(&format!("ir_version = {}\n", ir.ir_version));
    out.push_str(&format!("app = \"{}\"\n", ir.app.name));
    out.push_str(&format!("app_version = \"{}\"\n", ir.app.version));
    out.push_str(&format!("ir_hash = \"sha256:{}\"\n", ir.content_hash));
    let drivers: Vec<String> = ir.app.drivers.iter().map(|d| format!("\"{d}\"")).collect();
    out.push_str(&format!("drivers = [{}]\n", drivers.join(", ")));
    out.push_str("\n[sources]\n");
    for f in files {
        out.push_str(&format!(
            "\"{}\" = \"sha256:{}\"\n",
            f.path,
            sha256_hex(f.text.as_bytes())
        ));
    }
    out
}

/// The `ir_hash` recorded in a lock file, if present.
pub fn recorded_ir_hash(lock: &str) -> Option<&str> {
    lock.lines()
        .find_map(|l| l.strip_prefix("ir_hash = \"sha256:"))
        .and_then(|rest| rest.strip_suffix('"'))
}
